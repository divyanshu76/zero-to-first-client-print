#!/usr/bin/env python3
"""Write human-readable inventories from the machine-readable validation JSON.

Inputs : validation/prompts_final_print.json, audit/content_inventory.json
Outputs: reports/PROMPT_INVENTORY.md, reports/TEMPLATE_CALCULATOR_FIGURE_INVENTORY.md
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2] / "production"
P = json.loads((ROOT / "validation/prompts_final_print.json").read_text())
INV = json.loads((ROOT / "audit/content_inventory.json").read_text())


def esc(s):
    return s.replace("|", "\\|")


lines = ["# AI Prompt Inventory — 141 prompts", "",
         "Generated by `scripts/write_inventory_reports.py` from `validation/prompts_final_print.json` "
         "(output of `scripts/validate_prompts.py` on the paperback source).", "",
         "## Validation summary", ""]
for k, v in P["summary"].items():
    lines.append(f"- **{k}**: {v}")
lines += ["", "| Check | Result | Detail |", "|---|---|---|"]
lines += [f"| {c['check']} | {c['status']} | {esc(c['detail'])} |" for c in P["checks"]]
lines += ["", "## All prompts", "",
          "Body hash = first 16 hex of SHA-256 of the prompt instruction text; it must stay identical to the original.", "",
          "| # | ID | Title | Category | Location | Placeholders | Body hash |", "|---|---|---|---|---|---|---|"]
for i, p in enumerate(P["prompts"], 1):
    lines.append(f"| {i} | #{p['id']} | {esc(p['title'])} | {esc(p['category']) or '—'} | {p['location']} | "
                 f"{esc(' '.join(p['placeholders'])) or '—'} | `{p['body_sha256']}` |")
(ROOT / "reports/PROMPT_INVENTORY.md").write_text("\n".join(lines) + "\n")

t = ["# Template, Calculator and Figure Inventory", "",
     "Generated from `audit/content_inventory.json` (original manuscript reconstruction).", "",
     "## 20 templates (Bonus B)", "", "| No. | Template | Fields / rows in original | Paperback treatment (planned) |", "|---|---|---|---|"]
TREAT = {
    "01": "Scoring matrix with blank write-in cells for Idea A/B/C",
    "02": "Skill table with 6 blank write-in rows",
    "04": "Competitor grid with 8 blank write-in rows",
    "06": "Basic / Standard / Premium grid with write-in cells",
    "07": "Input/result sheet + the Chapter 6 formulas printed",
    "09": "Page-plan grid with write-in column",
    "12": "Line-item table with blank rows + totals block",
    "14": "Onboarding checklist with tick boxes and Due column",
    "16": "Invoice fields + blank line-item rows",
    "17": "Example record + blank tracker sheet (landscape-style rows)",
    "18": "Example record + blank CRM sheet",
    "19": "Example record + blank follow-up sheet",
    "20": "30-day planner sheet (Day, Task, Done, Actual hours, Note)",
}
for x in INV["templates"]:
    t.append(f"| {x['number']} | {esc(x['title'])} | {len(x['fields_or_rows'])} | "
             f"{TREAT.get(x['number'], 'Fill-in form: label + example left, 2 ruled writing lines right')} |")
t += ["", "## 7 calculator sheets (Bonus C)", "",
      "The original Bonus C is a one-page index of an Excel workbook (removed). The paperback prints each sheet "
      "as a worksheet using only formulas already stated in the manuscript.", "",
      "| Sheet | When | Inputs | Outputs | Formula source in the manuscript |", "|---|---|---|---|---|"]
SRC = {
    "Hourly Rate": "Ch 6 'Cost और rate calculation': Minimum hourly rate = (personal need + business costs + tax reserve) ÷ billable hours",
    "Project Pricing": "Ch 6 project example: hours × (1 + buffer) × rate + direct costs = floor price; Template 07",
    "Profit": "Ch 6 'Profit margin = (Revenue − Direct costs − Value of your time) ÷ Revenue'; Ch 8 case study 'Effective rate = revenue ÷ total hours'",
    "Monthly Target": "Ch 6 Figure 14 (clients × price = revenue) + Ch 10 conversion rates, worked backwards",
    "Lead Conversion": "Ch 10 'Performance metrics और conversion calculation' table (reply, call, proposal, close rates)",
    "Client Tracker": "Ch 10 lead tracking status values; Template 17 columns",
    "Demand Score": "Ch 4 'Demand Scoring Calculator' (Pain, Frequency, Spending, Reach, Fit, each 0–5; 16+ Go, 10–15 Refine, under 10 Drop)",
}
for c in INV["calculators"]:
    t.append(f"| {c['sheet']} | {esc(c['when'])} | {esc(c['inputs'])} | {esc(c['outputs'])} | {esc(SRC.get(c['sheet'], ''))} |")
t += ["", "## 24 diagrams", "", "| Fig. | Source page (A4) | Section | Caption | Rebuild status |", "|---|---|---|---|---|"]
built = {p.stem.split("-")[1].lstrip("0") for p in (ROOT / "design-system/diagrams").glob("fig-*.html")}
for f in INV["figures"]:
    t.append(f"| {f['figure']} | {f['source_page']} | {esc(f['section'])} | {esc(f['caption'][:110])} | "
             f"{'rebuilt as vector (24/24 verified)' if f['figure'] in built else 'NOT REBUILT'} |")
t += ["", f"## Other preserved content", "",
      f"- 30-day action plan: {len(INV['thirty_day_plan_days'])} / 30 days present (Chapter 10 week tables)",
      f"- Glossary: {len(INV['glossary_terms'])} terms",
      f"- Appendix sources: {len(INV['appendix_sources'])} numbered sources (1–{INV['appendix_sources'][-1]})",
      f"- Workflow cards: {INV['totals']['workflow_cards']}; callout boxes: {INV['totals']['callouts']}"]
(ROOT / "reports/TEMPLATE_CALCULATOR_FIGURE_INVENTORY.md").write_text("\n".join(t) + "\n")
print("wrote reports/PROMPT_INVENTORY.md and reports/TEMPLATE_CALCULATOR_FIGURE_INVENTORY.md")
